    @Override
    public SGuiValidation validateForm() {
        SGuiValidation validation = moFields.validateFields();
        
        if (validation.isValid()) {
            SDbSpot spotSource = (SDbSpot) miClient.getSession().readRegistry(SModConsts.LOGU_SPOT, moKeySourceSpot.getValue());
            SDbSpot spotDestiny = (SDbSpot) miClient.getSession().readRegistry(SModConsts.LOGU_SPOT, moKeyDestinySpot.getValue());
            
            if (moKeyDeliveryType.getValue()[0] == SModSysConsts.LOGS_TP_DLY_NA) {
                validation.setMessage(SGuiConsts.ERR_MSG_FIELD_DIF + "'" + moKeyDeliveryType.getFieldName() + "'.");
                validation.setComponent(moKeyDeliveryType);
            }
            else if (moService != null && !moService.canBeGenericSourceSpot() && spotSource.isGeneric()) {
                validation.setMessage(SGuiConsts.ERR_MSG_FIELD_DIF + "'" + moKeySourceSpot.getFieldName() + "'.\n"
                        + "El lugar '" + spotSource.getName() + "' no se permite en el servicio '" + moService.getName() + "'.");
                validation.setComponent(moKeySourceSpot);
            }
            else if (moService != null && !moService.canBeGenericDestinySpot() && spotDestiny.isGeneric()) {
                validation.setMessage(SGuiConsts.ERR_MSG_FIELD_DIF + "'" + moKeyDestinySpot.getFieldName() + "'.\n"
                        + "El lugar '" + spotDestiny.getName() + "' no se permite en el servicio '" + moService.getName() + "'.");
                validation.setComponent(moKeyDestinySpot);
            }
            else if (SLibUtils.compareKeys(moKeyDestinySpot.getValue(), moKeySourceSpot.getValue())) {
                validation.setMessage(SGuiConsts.ERR_MSG_FIELD_REQ_EQUAL_NOT + "'" + moKeySourceSpot.getFieldName() + "' y '" + moKeyDestinySpot.getFieldName() + "'.");
                validation.setComponent(moKeyDestinySpot);
            }
            else if (moVehicle != null && moKeyVehicleType.getSelectedIndex() > 0 && moVehicle.getFkVehicleTypeId() != moKeyVehicleType.getValue()[0]) {
                validation.setMessage(SGuiConsts.ERR_MSG_FIELD_DIF + "'" + moKeyVehicleType.getFieldName() + "'.\n"
                        + SGuiConsts.ERR_MSG_FIELD_VAL_ + "'" + moKeyVehicle.getFieldName() + "' no corresponde con él.");
                validation.setComponent(moKeyDestinySpot);
            }
            else if (moBaseTariff == null && moBoolByBase.isSelected()) {
                validation.setMessage("No hay '" + SGuiUtils.getLabelName(jlBaseTariff) + "', por lo que no se puede seleccionar el campo '" + moBoolByBase.getText() + "'.");
                validation.setComponent(moBoolByBase);
            }
            else {
                // validate no duplicates and warn about new versions:
                
                try {
                    SDbFreightTariff[] tariffs = SDbFreightTariff.findTariffs(miClient.getSession(),
                            moRegistry.getPkFreightTariffId(), getTariffType(),
                            moKeyService.getValue()[0], moKeyDeliveryType.getValue()[0],
                            moKeySourceSpot.getValue()[0], moKeyDestinySpot.getSelectedIndex() <= 0 ? 0 : moKeyDestinySpot.getValue()[0],
                            moKeyModeOfTransportType.getValue()[0], moKeyShippingSizeType.getValue()[0], 
                            moKeyVehicleType.getSelectedIndex() <= 0 ? 0 : moKeyVehicleType.getValue()[0], moKeyFreightClass.getValue()[0],
                            moKeyCarrier.getSelectedIndex()<= 0 ? 0 : moKeyCarrier.getValue()[0], moKeyVehicle.getSelectedIndex() <= 0 ? 0 : moKeyVehicle.getValue()[0]);
                    
                    if (tariffs != null && tariffs.length > 0) {
                        SDbFreightTariff tariff = tariffs[0]; // most recent tariff
                        
                        if (!moDateTariffStart.getValue().after(tariff.getStart())) {
                            validation.setMessage("<html><b>IMPORTANTE:</b><br>"
                                    + "Los datos de esta tarifa coinciden con los de la tarifa '" + tariff.getCode() + "'.<br>"
                                    + "<b>No puede haber múltiples tarifas con los mismos datos e inicios de vigencia.</b><br>"
                                    + "Si realmente desea crear una nueva versión de la tarifa '" + tariff.getCode() + "', "
                                    + "capture en '" + moDateTariffStart.getFieldName() + "' una fecha posterior a '" + SLibUtils.DateFormatDate.format(tariff.getStart()) + "'.</html>");
                            validation.setComponent(moDateTariffStart);
                        }
                        else {
                            if (miClient.showMsgBoxConfirm("<html><b>¡CUIDADO!</b><br>"
                                    + "<b>Revise con atención la siguiente información:</b><br>"
                                    + "¿Está seguro que desea crear una nueva versión de la tarifa '" + tariff.getCode() + "', "
                                    + "con inicio de vigencia el '" + SLibUtils.DateFormatDate.format(moDateTariffStart.getValue()) + "'?</html>") != JOptionPane.YES_OPTION) {
                                validation.setMessage("Revise los datos de esta tarifa para que no coincidan con los de la tarifa '" + tariff.getCode() + "'.");
                            }
                        }
                    }
                }
                catch (Exception e) {
                    validation.setMessage(e.getMessage());
                }
            }
        }

        return validation;
    }

