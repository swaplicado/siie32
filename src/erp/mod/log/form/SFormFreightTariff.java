    @Override
    public void itemStateChanged(ItemEvent e) {
        if (!mbUpdatingFields) {
            if (e.getSource() instanceof SBeanFieldKey && e.getStateChange() == ItemEvent.SELECTED) {
                SBeanFieldKey field = (SBeanFieldKey) e.getSource();

                if (field == moKeyCarrier) {
                    itemStateChangedCarrier();
                }
                else if (field == moKeyVehicle) {
                    itemStateChangedVehicle();
                }
                else if (field == moKeyService) {
                    itemStateChangedService();
                }
                else if (field == moKeyDeliveryType) {
                    itemStateChangedDeliveryType();
                }
                else if (field == moKeySourceSpot) {
                    itemStateChangedSourceSpot();
                }
                else if (field == moKeyDestinySpot) {
                    itemStateChangedDestinySpot();
                }
                else if (field == moKeyVehicleType) {
                    itemStateChangedVehicleType();
                }
                else if (field == moKeyFreightClass) {
                    itemStateChangedFreightClass();
                }

                boolean lookup = field == moKeyService || field == moKeyDeliveryType ||
                        field == moKeySourceSpot || field == moKeyDestinySpot ||
                        field == moKeyModeOfTransportType || field == moKeyShippingSizeType ||
                        field == moKeyVehicleType || field == moKeyFreightClass;

                if (lookup) {
                    lookupBaseTariff();
                }
            }
            else if (e.getSource() instanceof SBeanFieldRadio && e.getStateChange() == ItemEvent.SELECTED) {
                SBeanFieldRadio field = (SBeanFieldRadio) e.getSource();

                if (field == moRadTypeBase || field == moRadTypeCarrier || field == moRadTypeVehicle) {
                    itemStateChangedType();
                }
            }
            else if (e.getSource() instanceof SBeanFieldBoolean) {
                SBeanFieldBoolean field = (SBeanFieldBoolean) e.getSource();

                if (field == moBoolByBase) {
                    itemStateChangedByBase();
                }
            }
        }
    }
