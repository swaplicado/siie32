    private void itemStateChangedCarrier() {
        try {
            mbUpdatingFields = true;
            
            if (moKeyCarrier.getSelectedIndex() <= 0) {
                moCarrier = null;
                jtfCarrierFiscalId.setText("");
            }
            else {
                moCarrier = (SDbBizPartner) miClient.getSession().readRegistry(SModConsts.BPSU_BP, moKeyCarrier.getValue());
                jtfCarrierFiscalId.setText(moCarrier.getFiscalId());
                jtfCarrierFiscalId.setCaretPosition(0);
            }

            if (moRadTypeVehicle.isSelected()) {
                if (moKeyCarrier.getSelectedIndex() <= 0) {
                    moKeyVehicle.setEnabled(false);

                    moKeyVehicle.removeAllItems();
                }
                else {
                    moKeyVehicle.setEnabled(true);

                    SGuiParams params = new SGuiParams(moKeyVehicleType.getSelectedIndex() <= 0 ? 0 : moKeyVehicleType.getValue()[0]);
                    params.setKey(moKeyCarrier.getValue());
                    miClient.getSession().populateCatalogue(moKeyVehicle, SModConsts.LOG_VEH, 0, params);
                }
            }
            else {
                moKeyVehicle.setEnabled(false);

                moKeyVehicle.removeAllItems();
            }
        }
        catch (Exception e) {
            SLibUtils.showException(this, e);
        }
        finally {
            mbUpdatingFields = false;
        }
    }
    
