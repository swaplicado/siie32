    private String getTariffType() {
        String type = "";
        
        if (moRadTypeCarrier.isSelected()) {
            type = SDbFreightTariff.TYPE_CARRIER;
        }
        else if (moRadTypeVehicle.isSelected()) {
            type = SDbFreightTariff.TYPE_VEHICLE;
        }
        else {
            type = SDbFreightTariff.TYPE_BASE;
        }
        
        return type;
    }
    
    private void lookupBaseTariff() {
        try {
            boolean lookup = moKeyService.getSelectedIndex() > 0 && moKeyDeliveryType.getSelectedIndex() > 0 &&
                    moKeySourceSpot.getSelectedIndex() > 0 && /*moKeyDestinySpot.getSelectedIndex() > 0 &&*/
                    moKeyModeOfTransportType.getSelectedIndex() > 0 && moKeyShippingSizeType.getSelectedIndex() > 0 &&
                    /*moKeyVehicleType.getSelectedIndex() > 0 &&*/ moKeyFreightClass.getSelectedIndex() > 0;

            if (lookup) {
                moBaseTariff = SDbFreightTariff.lookupBaseTariff(miClient.getSession(),
                        moRegistry.getPkFreightTariffId(),
                        moKeyService.getValue()[0], moKeyDeliveryType.getValue()[0],
                        moKeySourceSpot.getValue()[0], moKeyDestinySpot.getSelectedIndex() <= 0 ? 0 : moKeyDestinySpot.getValue()[0],
                        moKeyModeOfTransportType.getValue()[0], moKeyShippingSizeType.getValue()[0], 
                        moKeyVehicleType.getSelectedIndex() <= 0 ? 0 : moKeyVehicleType.getValue()[0], moKeyFreightClass.getValue()[0]);
            }
            else {
                moBaseTariff = null;
            }
        }
        catch (Exception e) {
            SLibUtils.showException(this, e);
        }
        finally {
            if (moBaseTariff == null) {
                moCurBaseTariff.getField().resetField();
                moDateBaseTariffStart.resetField();
                jtfBaseTariffCode.setText("");
                jlBaseTariffFound.setText("No hay tarifas base coincidentes");
                jlBaseTariffFound.setIcon(new javax.swing.ImageIcon(getClass().getResource("/erp/img/icon_view_warn.png")));
            }
            else {
                moCurBaseTariff.getField().setValue(moBaseTariff.getTariff());
                moDateBaseTariffStart.setValue(moBaseTariff.getStart());
                jtfBaseTariffCode.setText(moBaseTariff.getCode());
                jlBaseTariffFound.setText("¡Se encontró una tarifa base coincidente!");
                jlBaseTariffFound.setIcon(new javax.swing.ImageIcon(getClass().getResource("/erp/img/icon_view_lig_gre.png")));
            }
        }
    }

