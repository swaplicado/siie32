    private void itemStateChangedDeliveryType() {
        try {
            mbUpdatingFields = true;
            
            if (moService == null || moKeyDeliveryType.getSelectedIndex() <= 0) {
                moKeySourceSpot.setEnabled(false);
                moKeyDestinySpot.setEnabled(false);

                moKeySourceSpot.removeAllItems();
                itemStateChangedSourceSpot();
                
                moKeyDestinySpot.removeAllItems();
                itemStateChangedDestinySpot();
            }
            else {
                int subtypeSource = 0;
                int subtypeDestiny = 0;
                SGuiParams paramsSource = null;
                SGuiParams paramsDestiny = null;
                
                if (moService.isFreightOutgoing()) {
                    paramsSource = new SGuiParams(SModConsts.LOGU_SPOT_COB, miClient.getSession().getConfigCompany().getCompanyId());
                    
                    subtypeDestiny = moKeyDeliveryType.getValue()[0];
                }
                else if (moService.isFreightIncoming()) {
                    paramsDestiny = new SGuiParams(SModConsts.LOGU_SPOT_COB, miClient.getSession().getConfigCompany().getCompanyId());
                    
                    subtypeSource = moKeyDeliveryType.getValue()[0];
                }
                
                moKeySourceSpot.setEnabled(true);
                moKeyDestinySpot.setEnabled(true);

                miClient.getSession().populateCatalogue(moKeySourceSpot, SModConsts.LOGU_SPOT, subtypeSource, paramsSource);
                
                if (moKeySourceSpot.getItemCount() == 2) {
                    moKeySourceSpot.setSelectedIndex(1);
                    itemStateChangedSourceSpot();
                }
                
                miClient.getSession().populateCatalogue(moKeyDestinySpot, SModConsts.LOGU_SPOT, subtypeDestiny, paramsDestiny);
                
                if (moKeyDestinySpot.getItemCount() == 2) {
                    moKeyDestinySpot.setSelectedIndex(1);
                    itemStateChangedDestinySpot();
                }
            }
        }
        catch (Exception e) {
            SLibUtils.showException(this, e);
        }
        finally {
            mbUpdatingFields = false;
        }
    }
    
