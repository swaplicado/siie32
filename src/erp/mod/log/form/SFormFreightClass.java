    @Override
    public void setRegistry(SDbRegistry registry) throws Exception {
        moRegistry = (SDbFreightClass) registry;

        mnFormResult = SLibConsts.UNDEFINED;
        mbFirstActivation = true;

        removeAllListeners();
        reloadCatalogues();
        setFormEditable(true);

        if (moRegistry.isRegistryNew()) {
            moRegistry.initPrimaryKey();
            jtfRegistryKey.setText("");
        }
        else {
            jtfRegistryKey.setText(SLibUtils.textKey(moRegistry.getPrimaryKey()));
        }

        moTextCode.setValue(moRegistry.getCode());
        moTextName.setValue(moRegistry.getName());
        
        switch (moRegistry.getClassType()) {
            case SDbFreightClass.TYPE_HIGH:
                moRadTypeHigh.setSelected(true);
                break;
            case SDbFreightClass.TYPE_LOW:
                moRadTypeLow.setSelected(true);
                break;
            default:
                moRadTypeMiddle.setSelected(true);
        }
        
        if (moRegistry.isRegistryNew()) { }

        addAllListeners();
    }

    @Override
    public SDbRegistry getRegistry() throws Exception {
        SDbFreightClass registry = moRegistry.clone();

        if (registry.isRegistryNew()) {}

        registry.setCode(moTextCode.getValue());
        registry.setName(moTextName.getValue());
        
        if (moRadTypeHigh.isSelected()) {
            registry.setClassType(SDbFreightClass.TYPE_HIGH);
        }
        else if (moRadTypeLow.isSelected()) {
            registry.setClassType(SDbFreightClass.TYPE_LOW);
        }
        else {
            registry.setClassType(SDbFreightClass.TYPE_MIDDLE);
        }
        
        return registry;
    }

