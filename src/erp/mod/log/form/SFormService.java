    private void actionPerformedPickItem() {
        SGuiOptionPicker picker = miClient.getSession().getModule(SModConsts.MOD_ITM_N).getOptionPicker(SModConsts.ITMU_ITEM, SLibConsts.UNDEFINED, null);
        picker.resetPicker();
        picker.setPickerVisible(true);

        if (picker.getPickerResult() == SGuiConsts.FORM_RESULT_OK) {
            int[] key = (int[]) picker.getOption();

            if (key != null) {
                if (key[0] != SLibConsts.UNDEFINED) {
                    moKeyItem.setValue(new int[] { key[0] });
                }
            }
        }
    }

    public void itemStateChangedItem() {
        if (moKeyItem.getSelectedIndex() <= 0) {
            mnItemUnitId = 0;
            moKeyUnit.resetField();
            
            jtfItemUnit.setText("");
        }
        else {
            mnItemUnitId = (int) miClient.getSession().readField(SModConsts.ITMU_ITEM, moKeyItem.getValue(), SDbItem.FIELD_UNIT);
            moKeyUnit.setValue(new int[] { mnItemUnitId });
            
            jtfItemUnit.setText(((String) miClient.getSession().readField(SModConsts.ITMU_UNIT, new int[] { mnItemUnitId }, SDbRegistry.FIELD_NAME)));
            jtfItemUnit.setCaretPosition(0);
        }
    }

    @Override
    public void addAllListeners() {
        jbPickItem.addActionListener(this);
        moKeyItem.addItemListener(this);
    }

    @Override
    public void removeAllListeners() {
        jbPickItem.removeActionListener(this);
        moKeyItem.removeItemListener(this);
    }

    @Override
    public void reloadCatalogues() {
        miClient.getSession().populateCatalogue(moKeyServiceType, SModConsts.LOGS_TP_SERVICE, 0, null);
        miClient.getSession().populateCatalogue(moKeyItem, SModConsts.ITMU_ITEM, 0, null);
        miClient.getSession().populateCatalogue(moKeyUnit, SModConsts.ITMU_UNIT, 0, null);
    }

    @Override
    public void setRegistry(SDbRegistry registry) throws Exception {
        moRegistry = (SDbService) registry;

        mnFormResult = SLibConsts.UNDEFINED;
        mbFirstActivation = true;

        removeAllListeners();
        reloadCatalogues();
        setFormEditable(true);

        if (moRegistry.isRegistryNew()) {
            moRegistry.initPrimaryKey();
            jtfRegistryKey.setText("");
        }
        else {
            jtfRegistryKey.setText(SLibUtils.textKey(moRegistry.getPrimaryKey()));
        }

        moKeyServiceType.setValue(new int[] { moRegistry.getFkServiceTypeId() });
        moTextCode.setValue(moRegistry.getCode());
        moTextName.setValue(moRegistry.getName());
        moKeyItem.setValue(new int[] { moRegistry.getFkItemId()});
        itemStateChangedItem();
        moKeyUnit.setValue(new int[] { moRegistry.getFkUnitId()});
        
        moPanelCostCenter.setSelectedAccount(moRegistry.getFkCostCenterId_n() == 0 ? null :
                new SAccount(moRegistry.getFkCostCenterId_n(),
                        (String) miClient.getSession().readField(SModConsts.FIN_CC, new int[] { moRegistry.getFkCostCenterId_n()}, SDbRegistry.FIELD_CODE),
                        "", false, 0, 0));

        if (moRegistry.isRegistryNew()) { }

        addAllListeners();
    }

    @Override
    public SDbRegistry getRegistry() throws Exception {
        SDbService registry = moRegistry.clone();

        if (registry.isRegistryNew()) { }

        registry.setCode(moTextCode.getValue());
        registry.setName(moTextName.getValue());
        registry.setFkServiceTypeId(moKeyServiceType.getValue()[0]);
        registry.setFkItemId(moKeyItem.getValue()[0]);
        registry.setFkUnitId(moKeyUnit.getValue()[0]);
        registry.setFkCostCenterId_n(moPanelCostCenter.getSelectedAccount() != null ? moPanelCostCenter.getSelectedAccount().getAccountId() : SDataConstantsSys.NA);
        
        return registry;
    }

    @Override
    public SGuiValidation validateForm() {
        SGuiValidation validation = moFields.validateFields();
        
        if (validation.isValid()) {
            if (mnItemUnitId != moKeyUnit.getValue()[0] && miClient.showMsgBoxConfirm("El valor del campo '" + moKeyUnit.getFieldName() + "' no es el predeterminado del campo '" + moKeyItem.getFieldName() + "',"
                    + "\n" + SGuiConsts.MSG_CNF_CONT_OMIT_VAL) != JOptionPane.YES_OPTION) {
                validation.setMessage(SGuiConsts.ERR_MSG_FIELD_DIF + "'" + moKeyUnit.getFieldName() + "'.");
                validation.setComponent(moKeyUnit);
            }
            else {
                validation = moPanelCostCenter.validatePanel();
            }
        }

        return validation;
    }

    @Override
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() instanceof JButton) {
            JButton button = (JButton) e.getSource();
            
            if (button == jbPickItem) {
                actionPerformedPickItem();
            }
        }
    }

    @Override
    public void itemStateChanged(ItemEvent e) {
        if (e.getSource() instanceof SBeanFieldKey && e.getStateChange() == ItemEvent.SELECTED) {
            SBeanFieldKey field = (SBeanFieldKey) e.getSource();
            
            if (field == moKeyItem) {
                itemStateChangedItem();
            }
        }
    }
