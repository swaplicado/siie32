    private void populateOptions() {
        try {
            ArrayList<SGridRow> rows = new ArrayList<>();
            String search = moTextSearch.getValue();
            
            if (search.length() < mnMinLength) {
                showSearchInfo();
            }
            else {
                String where = "";

                if (moRadByZipCode.isSelected()) {
                    where = "nei.zip_code LIKE '" + search + "%'";
                }
                else if (moRadByNeighborhood.isSelected()) {
                    where = "nei.description LIKE '%" + search + "%'";
                }
                else if (moRadByLocality.isSelected()) {
                    where = "loc.description LIKE '%" + search + "%'";
                }
                else if (moRadByCounty.isSelected()) {
                    where = "cou.description LIKE '%" + search + "%'";
                }
                else if (moRadByState.isSelected()) {
                    where = "sta.sta LIKE '" + search + "%'";
                }

                String sql = "SELECT "
                        + "zip.id_zip_code AS _zip_code, "
                        + "nei.nei_code AS _nei_code, nei.description AS _nei_descrip, nei.id_nei_zip_code, "
                        + "loc.id_locality_code AS _loc_code, loc.description AS _loc_descrip, "
                        + "cou.id_county_code AS _cou_code, cou.description AS _cou_descrip, "
                        + "zip.id_sta_code AS _sta_code, sta.sta AS _sta_descrip, sta.id_sta "
                        + "FROM "
                        + "erp.locs_bol_zip_code AS zip "
                        + "INNER JOIN erp.locu_sta AS sta ON sta.sta_code = zip.id_sta_code "
                        + "LEFT OUTER JOIN erp.locs_bol_county AS cou ON cou.id_county_code = zip.county_code AND cou.id_sta_code = zip.id_sta_code AND NOT cou.b_del "
                        + "LEFT OUTER JOIN erp.locs_bol_locality AS loc ON loc.id_locality_code = zip.locality_code AND loc.id_sta_code = zip.id_sta_code AND NOT loc.b_del "
                        + "LEFT OUTER JOIN erp.locs_bol_nei_zip_code AS nei ON nei.zip_code = zip.id_zip_code AND NOT nei.b_del "
                        + "WHERE "
                        + "NOT zip.b_del AND NOT sta.b_del AND " + where + " "
                        + "ORDER BY "
                        + "_zip_code, "
                        + "_nei_code, _nei_descrip, nei.id_nei_zip_code, "
                        + "_loc_code , _loc_descrip, "
                        + "_cou_code, _cou_descrip, "
                        + "_sta_code, _sta_descrip, sta.id_sta;";

                try (ResultSet resultSet = miClient.getSession().getStatement().executeQuery(sql)) {
                    while (resultSet.next()) {
                        rows.add(new SRowNeighborhood(resultSet.getInt("_zip_code"), resultSet.getInt("sta.id_sta"), resultSet.getInt("nei.id_nei_zip_code"),
                                resultSet.getString("_nei_code"), resultSet.getString("_nei_descrip"),
                                resultSet.getString("_loc_code"), resultSet.getString("_loc_descrip"),
                                resultSet.getString("_cou_code"), resultSet.getString("_cou_descrip"),
                                resultSet.getString("_sta_code"), resultSet.getString("_sta_descrip")));
                    }
                }
                
                jlSearchInfo.setText("Opciones encontradas: " + SLibUtils.DecimalFormatInteger.format(rows.size()));
            }
            
            moOptionsGrid.populateGrid(new Vector<>(rows));
            addPickerListeners();
        }
        catch (Exception e) {
            SLibUtils.showException(this, e);
        }
    }
    
    private void actionPerformedSearch(final boolean validate) {
        if (validate) {
            String search = moTextSearch.getValue();
            
            if (search.length() < mnMinLength) {
                miClient.showMsgBoxWarning("Deben introducirse al menos " + mnMinLength + " para realizar la búsqueda.");
                moTextSearch.requestFocusInWindow();
            }
        }
        
        populateOptions();
    }
    
    private void actionPerformedClear() {
        moTextSearch.resetField();
        moTextSearch.requestFocusInWindow();
        populateOptions();
    }
    
    private void itemStateChangedFilterBy() {
        // update minimum length:
        
        if (moRadByZipCode.isSelected()) {
            mnMinLength = 2;
        }
        else if (moRadByNeighborhood.isSelected()) {
            mnMinLength = 3;
        }
        else if (moRadByLocality.isSelected()) {
            mnMinLength = 3;
        }
        else if (moRadByCounty.isSelected()) {
            mnMinLength = 3;
        }
        else if (moRadByState.isSelected()) {
            mnMinLength = 3;
        }
        
        showSearchInfo();
        
        // clear options:
        
        moTextSearch.resetField();
        populateOptions();
    }
    
