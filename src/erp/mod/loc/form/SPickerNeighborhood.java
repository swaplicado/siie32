    @Override
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() instanceof JButton) {
            JButton button = (JButton) e.getSource();
            
            if (button == jbSearch) {
                actionPerformedSearch(true);
            }
            else if (button == jbClear) {
                actionPerformedClear();
            }
        }
    }

    @Override
    public void itemStateChanged(ItemEvent e) {
        if (e.getSource() instanceof SBeanFieldRadio && e.getStateChange() == ItemEvent.SELECTED) {
            SBeanFieldRadio field = (SBeanFieldRadio) e.getSource();
            
            if (field == moRadByZipCode || field == moRadByNeighborhood || field == moRadByLocality || field == moRadByCounty) {
                itemStateChangedFilterBy();
            }
        }
    }

