    private void renderNotes() {
        String notes = "";
        for (SDbStockValuationMvtNote note : mlNotes) {
            notes += note.getNotes() + "\n";
        }

        jtaNotes.setText(notes);
    }

    public void resetForm() {
        mnFormResult = SLibConsts.UNDEFINED;
        mbFirstActivation = true;

        jtaNotes.setText("");
    }
    
