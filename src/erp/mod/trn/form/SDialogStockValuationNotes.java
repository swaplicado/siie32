    @Override
    public void setValue(final int type, final Object value) {
        resetForm();
        if (value != null) {
            Integer idMvt = (Integer) value;
            if (idMvt > 0) {
                try {
                    mlNotes = SStockValNotesUtils.getAllStockValuationMvtNotes(miClient.getSession(), idMvt);
                    if (mlNotes != null && !mlNotes.isEmpty()) {
                        renderNotes();
                    }
                    else {
                        jtaNotes.setText("");
                    }
                }
                catch (Exception ex) {
                    jtaNotes.setText("");
                    Logger.getLogger(SDialogStockValuationNotes.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
        }
    }

