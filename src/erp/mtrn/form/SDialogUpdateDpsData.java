    private void doLogger(int companyPk, int yearId, int docId, String originalDate, String newDate, String originalCfdUse, String newCfdUse, String usernameModify) {
        try {
            Logger logger = Logger.getLogger(SDialogUpdateDpsData.class.getName());
            
            // Crear FileHandler que escribirá en un archivo .log
            FileHandler fileHandler = new FileHandler("logs/logsPurchaseOrders.log", true);
            logger.setUseParentHandlers(false);
            fileHandler.setFormatter(new SimpleFormatter());
            
            // Agregar el handler al logger
            logger.addHandler(fileHandler);
            
            // Ejemplos de registros
            logger.log(Level.INFO, 
                    "Purchase order: companyPk - {0}, yearId - {1}, docId - {2}, originalDate - {3}, newDate - {4}, originalCfdUse - {5}, newCfdUse - {6}, user mod. - {7}", 
                    new Object[]{String.valueOf(companyPk), String.valueOf(yearId), String.valueOf(docId), originalDate, newDate, originalCfdUse, newCfdUse, usernameModify}
            );
            
            // Cerrar el handler
            fileHandler.close();
            
        } catch (IOException e) {
            Logger.getLogger(SDialogUpdateDpsData.class.getName()).log(Level.SEVERE, null, e);
        }
    }
    
    private boolean updateDpsDateAndCfdUse() {
        int response;
        try {
            response = SDataUtilities.updateDpsDateAndCfdUse(miClient, moDps.getPkYearId(), moDps.getPkDocId(), moFieldDate.getDate(), moFieldFisDataCfdiUsage.getFieldValue().toString());
            String originalDate = miClient.getSessionXXX().getFormatters().getDbmsDateFormat().format(moDps.getDate());
            String newDate = miClient.getSessionXXX().getFormatters().getDbmsDateFormat().format(moFieldDate.getDate());
            doLogger(moDps.getFkCompanyBranchId(), moDps.getPkYearId(), moDps.getPkDocId(), originalDate, newDate, moDps.getDbmsDataDpsCfd().getCfdiUsage(), 
                    moFieldFisDataCfdiUsage.getFieldValue().toString(), miClient.getSession().getUser().getName());
        } catch (Exception ex) {
            Logger.getLogger(SDialogUpdateDpsData.class.getName()).log(Level.SEVERE, null, ex);
            SLibUtilities.printOutException(this, ex);
            return false;
        }
        
        try {
            ObjectMapper mapper = new ObjectMapper();
            JsonNode config = mapper.readTree(SCfgUtils.getParamValue(miClient.getSession().getStatement(), SDataConstantsSys.CFG_PARAM_SWAP_SERVICES_CONFIG));
            String baseUrl = SAuthJsonUtils.getValueOfElementAsText(config, SSwapConsts.CFG_OBJ_TXN_SRV, SSwapConsts.CFG_ATT_URL);
            String url = baseUrl + "/api/update-dps-date-and-cfd-use/";
            String jsonBody = "{"
                    + "\"siie_dps_doc_id\":" + moDps.getPkDocId() + ", "
                    + "\"siie_dps_year_id\":" + moDps.getPkYearId() + ", "
                    + "\"dpsDate\":\"" + miClient.getSessionXXX().getFormatters().getDbmsDateFormat().format(moFieldDate.getDate()) + "\", "
                    + "\"dpsCfdUse\":\"" + moFieldFisDataCfdiUsage.getFieldValue().toString()
                    + "\"}";
            
            String responseBody = SExportUtils.requestSwapService("", url, SHttpConsts.METHOD_POST, jsonBody, "", "", SSwapConsts.TIME_30_SEC);
            
            JsonNode responseJson = mapper.readTree(responseBody);

            if (responseJson.has("error")) {
                Logger.getLogger(SDialogUpdateDpsData.class.getName()).log(Level.SEVERE, null, "Respuesta inesperada desde el servicio de portal compras: " + responseBody);
                miClient.showMsgBoxWarning("Portal compras respondio: " + responseBody + ", queda pendiente la sincronización con el portal compras.");
            }
        }
        catch (Exception ex) {
            miClient.showMsgBoxWarning(ex.getMessage() + ". Queda pendiente la sincronización con el portal compras.");
        }
        
        return response == SLibConstants.DB_ACTION_ANNUL_OK;
    }

    private void actionOk() {
        SFormValidation validation = formValidate();

        if (validation.getIsError()) {
            if (validation.getComponent() != null) {
                validation.getComponent().requestFocus();
            }
            if (validation.getMessage().length() > 0) {
                miClient.showMsgBoxWarning(validation.getMessage());
            }
        }
        else {
            if (updateDpsDateAndCfdUse()) {
                mnFormResult = SLibConstants.FORM_RESULT_OK;
                setVisible(false);
            }
        }
    }

    private void actionCancel() {
        mnFormResult = SLibConstants.FORM_RESULT_CANCEL;
        setVisible(false);
    }

