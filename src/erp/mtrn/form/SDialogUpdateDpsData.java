    @Override
    public erp.lib.form.SFormValidation formValidate() {
        SFormValidation validation = new SFormValidation();

        for (SFormField field : mvFields) {
            if (!field.validateField()) {
                validation.setIsError(true);
                validation.setComponent(field.getComponent());
            }
        }

        if (!validation.getIsError()) {
            if (!SDataUtilities.isPeriodOpen(miClient, moDps.getDate())) {
                validation.setMessage(SLibConstants.MSG_ERR_GUI_PER_CLOSE + " (" + moDps.getDate().toString() + ")");
                validation.setComponent(jftDate);
                return validation;
            }
            
            if (!SDataUtilities.isPeriodOpen(miClient, moFieldDate.getDate())) {
                validation.setMessage(SLibConstants.MSG_ERR_GUI_PER_CLOSE + " (" + moFieldDate.getString() + ")");
                validation.setComponent(jftDate);
                return validation;
            }
            
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy");
            int year = Integer.parseInt(sdf.format(moFieldDate.getDate()));
            if (year != moDps.getPkYearId()) {
                validation.setMessage(SLibConstants.MSG_ERR_GUI_PER_CLOSE + " (" + moFieldDate.getString() + ")");
                validation.setComponent(jftDate);
            }
        }

        return validation;
    }

