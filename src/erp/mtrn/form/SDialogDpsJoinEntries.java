    private void windowActivated() {
        if (mbFirstTime) {
            mbFirstTime = false;
            moTablePane.getTable().requestFocus();
        }

        if (mbUndoMerge) {
            if (miClient.showMsgBoxConfirm("No se pueden unificar partidas si se tiene una unión anterior.\n"
                    + "¿Desea deshacer el proceso anterior?") == javax.swing.JOptionPane.YES_OPTION) {
                actionOk();
            }
            else {
                actionCancel();
            }
        }
    }

    private void renderDpsSourceEntries() {
        moTablePane.createTable();
        moTablePane.clearTableRows();

        if (moParamDpsSource != null) {
            String currencyCode = miClient.getSession().getSessionCustom().getCurrencyCode(new int[] { moParamDpsSource.getFkCurrencyId() });
            for (SDataDpsEntry entry : moParamDpsSource.getDbmsDpsEntries()) {
                if (!entry.getIsDeleted() && entry.getDbmsDpsLinksAsSource().isEmpty()) {
                    SDataEntryDpsMergeRow entryLink = null;

                    entryLink = new SDataEntryDpsMergeRow();
                    entryLink.setPkYearId(entry.getPkYearId());
                    entryLink.setPkDocId(entry.getPkDocId());
                    entryLink.setPkEntryId(entry.getPkEntryId());
                    entryLink.setSortingPosition(entry.getSortingPosition());
                    entryLink.setConceptKey(entry.getConceptKey());
                    entryLink.setConcept(entry.getConcept());
                    entryLink.setQuantity(entry.getOriginalQuantity());
                    entryLink.setUnitSymbol(entry.getDbmsOriginalUnitSymbol());
                    entryLink.setPrice(entry.getOriginalPriceUnitaryCy());
                    entryLink.setCurrencyCode(currencyCode);
                    entryLink.setSelected(false);
                    entryLink.prepareTableRow();

                    moTablePane.addTableRow(entryLink);
                }
            }

            moTablePane.renderTableRows();
            moTablePane.setTableRowSelection(0);

            ListSelectionModel selectionModel = moTablePane.getTable().getSelectionModel();
            selectionModel.addListSelectionListener(this);
            moTablePane.getTable().setSelectionModel(selectionModel);
            
            moDecimalEtyPrice.setEditable(false);
            moDecimalEtyPrice.setEnabled(false);
            moDecimalEtyPrice.setValue(0d);
            moTextCurrencyCode.setValue(currencyCode);
        }
    }

    private void actionSelectAll() {
        int index = moTablePane.getTable().getSelectedRow();
        SDataEntryDpsMergeRow entry = null;

        for (int i = 0; i < moTablePane.getTableGuiRowCount(); i++) {
            entry = (SDataEntryDpsMergeRow) moTablePane.getTableRow(i);
            entry.setSelected(true);
            entry.prepareTableRow();
        }

        moTablePane.renderTableRows();
        moTablePane.getTable().setRowSelectionInterval(index, index);

        enablePriceField();
    }

    private void actionUnselectAll() {
        int index = moTablePane.getTable().getSelectedRow();
        SDataEntryDpsMergeRow entry = null;

        for (int i = 0; i < moTablePane.getTableGuiRowCount(); i++) {
            entry = (SDataEntryDpsMergeRow) moTablePane.getTableRow(i);
            entry.setSelected(false);
            entry.prepareTableRow();
        }

        moTablePane.renderTableRows();
        moTablePane.getTable().setRowSelectionInterval(index, index);

        enablePriceField();
    }

    private void enablePriceField() {
        SDataEntryDpsMergeRow entry = null;

        boolean isFirstSelected = false;
        double dPrice = 0;
        mbIsPriceFieldEnabled = false;
        for (int i = 0; i < moTablePane.getTableGuiRowCount(); i++) {
            entry = (SDataEntryDpsMergeRow) moTablePane.getTableRow(i);
            if ((Boolean) entry.getValues().get(1)) {
                if (!isFirstSelected) {
                    isFirstSelected = true;
                    dPrice = entry.getPrice();
                }
                else {
                    if (dPrice != entry.getPrice()) {
                        mbIsPriceFieldEnabled = true;
                        break;
                    }
                }
            }
        }

        if (mbIsPriceFieldEnabled) {
            moDecimalEtyPrice.setEditable(true);
            moDecimalEtyPrice.setEnabled(true);
        }
        else {
            moDecimalEtyPrice.setEditable(false);
            moDecimalEtyPrice.setEnabled(false);
        }
    }

    private void actionOk() {
        SFormValidation validation = formValidate();

        if (validation.getIsError()) {
            if (validation.getComponent() != null) {
                validation.getComponent().requestFocus();
            }
            if (validation.getMessage().length() > 0) {
                miClient.showMsgBoxWarning(validation.getMessage());
            }
        }
        else {
            mnFormResult = SLibConstants.FORM_RESULT_OK;
            setVisible(false);
        }
    }

    private void actionCancel() {
        mnFormResult = SLibConstants.FORM_RESULT_CANCEL;
        setVisible(false);
    }

