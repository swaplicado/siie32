    @Override
    public erp.lib.form.SFormValidation formValidate() {
        int rows = 0;
        SFormValidation validation = new SFormValidation();
        int idItem = 0;
        int idUnit = 0;
        
        if (mbUndoMerge) {
            return validation;
        }

        enablePriceField();
        if (mbIsPriceFieldEnabled && moDecimalEtyPrice.getValue() <= 0) {
            validation.setMessage("Las partidas seleccionadas deben tener el mismo precio\n y este debe ser mayor a cero.");
            validation.setComponent(moTablePane.getTable());
            return validation;
        }

        for (int i = 0; i < moTablePane.getTableGuiRowCount(); i++) {
            SDataEntryDpsMergeRow entry = (SDataEntryDpsMergeRow) moTablePane.getTableRow(i);
            if ((Boolean) entry.getValues().get(1)) {
                rows++;
                if (idItem == 0) {
                    idItem = entry.getItemId();
                    idUnit = entry.getUnitId();
                }
                else if (idItem != entry.getItemId()) {
                    validation.setMessage("Las partidas seleccionadas deben pertenecer al mismo ítem.");
                    validation.setComponent(moTablePane.getTable());
                    break;
                }
                else if (idUnit != entry.getUnitId()) {
                    validation.setMessage("Las partidas seleccionadas deben pertenecer a la misma unidad de medida.");
                    validation.setComponent(moTablePane.getTable());
                    break;
                }
            }
        }

        if (!validation.getIsError()) {
            if (rows <= 1) {
                validation.setMessage("Se deben especificar al menos dos partidas para vinculación.");
                validation.setComponent(moTablePane.getTable());
            }
        }

        return validation;
    }

