    @Override
    public void setValue(int type, java.lang.Object value) {
        switch (type) {
            case SDataConstants.TRNX_DPS_SRC:
                moParamDpsSource = (SDataDps) value;
                moPanelDps.setDps(moParamDpsSource, null);

                if (moParamDpsSource.isDpsTypeContract()) {
                    jbSetEverything.setEnabled(false);
                }
                else {
                    jbSetEverything.setEnabled(true);
                }
                renderDpsSourceEntries();
                break;

            case CASE_UNDO_MERGE:
                mbUndoMerge = (Boolean) value;
                break;
                
            default:

        }
    }

    @Override
    public java.lang.Object getValue(int type) {
        Object value = null;

        switch (type) {
            case MERGED_ENTRIES:
                List<SDataEntryDpsMergeRow> entries = new ArrayList<>();
                for (int i = 0; i < moTablePane.getTableGuiRowCount(); i++) {
                    SDataEntryDpsMergeRow entry = (SDataEntryDpsMergeRow) moTablePane.getTableRow(i);
                    if ((Boolean) entry.getValues().get(1)) {
                        entries.add(entry);
                    }
                }
                value = entries;
                break;

            case CASE_ETY_PRICE:
                if (mbIsPriceFieldEnabled && moDecimalEtyPrice.getValue() >= 0) {
                    value = moDecimalEtyPrice.getValue();
                }
                else {
                    value = -1d;
                }
                break;

            default:
        }

        return value;
    }

